/**
 * Start a workflow run via SSE streaming.
 * Calls onEvent(type, data) for each SSE event received.
 * Returns a promise that resolves with the final workflow_complete data.
 */
export async function startWorkflowStream(projectId, onEvent) {
  const token = getStoredToken();
  const url   = `${API_URL}/api/agent/run-stream/${projectId}`;

  const response = await fetch(url, {
    method: 'GET',
    headers: {
      'Accept': 'text/event-stream',
      ...(token ? { 'Authorization': `Bearer ${token}` } : {}),
    },
  });

  if (!response.ok) {
    const body = await response.json().catch(() => ({}));
    const err = new Error(body?.message || `Agent stream error ${response.status}`);
    err.status = response.status;
    throw err;
  }

  const reader  = response.body.getReader();
  const decoder = new TextDecoder();
  let buffer = '';
  let currentEvent = null;
  let finalResult = null;

  while (true) {
    const { done, value } = await reader.read();
    if (done) break;

    buffer += decoder.decode(value, { stream: true });
    const lines = buffer.split('\n');
    buffer = lines.pop();

    for (const line of lines) {
      if (line.startsWith('event:')) {
        currentEvent = line.slice(6).trim();
      } else if (line.startsWith('data:')) {
        const rawData = line.slice(5).trim();
        try {
          const data = JSON.parse(rawData);
          if (currentEvent && currentEvent !== 'ping') {
            onEvent(currentEvent, data);
            if (currentEvent === 'workflow_complete') finalResult = data;
          }
        } catch (_) { /* ignore malformed JSON */ }
        currentEvent = null;
      }
      // SSE comment / keep-alive lines starting with ':' are ignored
    }
  }

  return finalResult;
}

// --- UNIFIED AGENT SERVICE ---

const agentService = {
  async startWorkflow(goal, projectId) {
    if (USE_MOCK) {
      _mockWorkflow  = buildGoalAwareWorkflow(goal);
      _mockTaskIndex = 0;
      _mockOutputs   = generateMockOutputs(goal, _mockWorkflow.tasks);
      _mockWorkflow.status = WorkflowStatus.RUNNING;
      _mockWorkflow.tasks[0].status = TaskStatus.RUNNING;
      return { workflowId: _mockWorkflow.id, workflow: { ..._mockWorkflow } };
    }
    throw new Error('In real mode, use startWorkflowStream() directly.');
  },

  advanceMock() {
    if (!_mockWorkflow) return;
    const tasks = _mockWorkflow.tasks;
    if (_mockTaskIndex < tasks.length) {
      const current = tasks[_mockTaskIndex];
      current.status = TaskStatus.COMPLETED;
      current.output = _mockOutputs[current.id] || { content: 'Generated output' };
      _mockTaskIndex++;
      if (_mockTaskIndex < tasks.length) {
        tasks[_mockTaskIndex].status = TaskStatus.RUNNING;
      } else {
        _mockWorkflow.status = WorkflowStatus.COMPLETED;
      }
    }
  },

  async getWorkflow(workflowId) {
    return _mockWorkflow ? { ..._mockWorkflow } : null;
  },

  async cancelWorkflow(workflowId) {
    if (_mockWorkflow) _mockWorkflow.status = WorkflowStatus.FAILED;
  },

  async getHistory(projectId) {
    if (USE_MOCK) {
      return (MOCK_PROJECTS || []).map(p => ({
        _id: `hist-${p.id}`, action: 'generation_completed',
        prompt: p.prompt, status: 'success',
        metadata: { workflowId: `wf-${p.id}`, taskCount: 4 },
        createdAt: new Date().toISOString(),
      }));
    }
    const data = await apiFetch(`/api/agent/history/${projectId}`);

    return data.data || [];
  },
};

export default agentService;
