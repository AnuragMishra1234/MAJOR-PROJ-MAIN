// --- MOCK: goal classification helpers ---

function classifyGoal(goal) {
  const g = (goal || '').toLowerCase();
  if (/website|landing|page|html|web|frontend/.test(g)) return 'website';
  if (/code|function|algorithm|api|script|program/.test(g)) return 'code';
  if (/essay|article|blog|report|write|content/.test(g)) return 'text';
  if (/analyze|analyse|data|insight|review/.test(g)) return 'analysis';
  return 'general';
}

function extractSubject(goal) {
  const g = goal || '';
  const m = g.match(/(?:for\s+(?:a\s+|an\s+)?|about\s+|called\s+|named\s+)([\w\s]{2,30})/i);
  if (m) return m[1].trim();
  const words = g.trim().split(/\s+/);
  return words.slice(-Math.min(3, words.length)).join(' ');
}

